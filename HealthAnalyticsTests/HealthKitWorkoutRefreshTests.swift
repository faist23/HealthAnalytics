//
//  HealthKitWorkoutRefreshTests.swift
//  HealthAnalyticsTests
//
//  The background pass refreshes workouts from HealthKit only (no Strava). A ride the
//  foreground already stored as its Strava copy must not gain a second, HealthKit-UUID
//  row: double load fakes tapers and back-to-back crashes.
//

import XCTest
import HealthKit
import SwiftData
@testable import HealthAnalytics

final class HealthKitWorkoutRefreshTests: XCTestCase {
    private let start = Date(timeIntervalSince1970: 1_790_000_000)

    private func healthKitRide(offset: TimeInterval = 0, minutes: Double = 60,
                               type: HKWorkoutActivityType = .cycling) -> WorkoutData {
        let s = start.addingTimeInterval(offset)
        return WorkoutData(workoutType: type, startDate: s, endDate: s.addingTimeInterval(minutes * 60),
                           duration: minutes * 60, totalEnergyBurned: nil, totalDistance: nil,
                           averagePower: nil, averageHeartRate: 140, source: .appleWatch)
    }

    private func storedStravaRide(offset: TimeInterval = 0, minutes: Double = 60) -> StravaImportData {
        StravaImportData(id: "strava-1", title: "Ride", workoutType: .cycling,
                         startDate: start.addingTimeInterval(offset), duration: minutes * 60,
                         distance: nil, power: 200, normalizedPower: 210, energy: nil, averageHeartRate: 140)
    }

    /// Review focus 1.
    func test_rideAlreadyStoredAsStrava_isNotUpsertedAgain() {
        let result = DataPersistenceActor.healthKitWorkoutsNotCoveredByStrava(
            [healthKitRide()], storedStrava: [storedStravaRide(offset: 30)])
        XCTAssertTrue(result.isEmpty)
    }

    func test_rideWithNoStravaCopy_isKept() {
        let result = DataPersistenceActor.healthKitWorkoutsNotCoveredByStrava(
            [healthKitRide()], storedStrava: [])
        XCTAssertEqual(result.count, 1)
    }

    func test_differentActivityAtTheSameTime_isKept() {
        let result = DataPersistenceActor.healthKitWorkoutsNotCoveredByStrava(
            [healthKitRide(type: .running)], storedStrava: [storedStravaRide()])
        XCTAssertEqual(result.count, 1, "A run overlapping a stored ride is a different workout")
    }

    func test_nonOverlappingRide_isKept() {
        let result = DataPersistenceActor.healthKitWorkoutsNotCoveredByStrava(
            [healthKitRide(offset: 6 * 3600)], storedStrava: [storedStravaRide()])
        XCTAssertEqual(result.count, 1)
    }

    // Generated by /ship test coverage audit (Claude Code), pass 1.
    // Value: protects=a HealthKit ride whose Strava copy is already stored gains no second row through
    //   upsertHealthKitWorkoutsOnly, while an uncovered HK ride is stored; fails_when=the source == "Strava"
    //   predicate, its window, or the StoredWorkout-to-StravaImportData mapping (type, start, duration) drifts,
    //   so every background refresh double-loads; why_new=the tests above call the pure filter with hand-built
    //   StravaImportData and never read a stored row; seam=none; no_claim=HealthKit fetch and the since/start
    //   window of refreshWorkoutsFromHealthKit (in-memory store; unit only)
    func test_backgroundUpsert_skipsTheStoredStravaTwin_andStoresTheUncoveredRide() async throws {
        let schema = Schema([StoredWorkout.self, StoredHealthMetric.self, StoredNutrition.self,
                             StoredIntentLabel.self, StoredFTPSnapshot.self])
        let container = try ModelContainer(for: schema, configurations: ModelConfiguration(isStoredInMemoryOnly: true))
        let persistence = DataPersistenceActor(modelContainer: container)

        // The foreground stored this ride as its Strava copy.
        await persistence.upsertRecentData(workouts: [], strava: [storedStravaRide(offset: 30)], sleep: [], hrv: [],
                                           rhr: [], steps: [], weight: [], nutrition: [], vo2max: [])

        let twin = healthKitRide()
        let uncovered = healthKitRide(offset: 6 * 3600)
        await persistence.upsertHealthKitWorkoutsOnly([twin, uncovered], since: start.addingTimeInterval(-3600))

        let ids = Set(try ModelContext(container).fetch(FetchDescriptor<StoredWorkout>()).map(\.id))
        XCTAssertEqual(ids, ["strava-1", uncovered.id.uuidString],
                       "The stored Strava ride must stay the only copy; the ride Strava doesn't have is stored once")
    }

    // Generated by /ship test coverage audit (Claude Code), pass 1.
    // Value: protects=a Strava twin that started just before `since` is still found, so its HealthKit ride gains no
    //   second row; fails_when=upsertHealthKitWorkoutsOnly's one-day lookback before `since` is dropped or narrowed;
    //   why_new=the test above stores its Strava ride after `since`, so the lookback never matters; seam=none;
    //   no_claim=how refreshWorkoutsFromHealthKit picks `since` (in-memory store; unit only)
    func test_backgroundUpsert_findsAStravaTwinThatStartedBeforeSince() async throws {
        let schema = Schema([StoredWorkout.self, StoredHealthMetric.self, StoredNutrition.self,
                             StoredIntentLabel.self, StoredFTPSnapshot.self])
        let container = try ModelContainer(for: schema, configurations: ModelConfiguration(isStoredInMemoryOnly: true))
        let persistence = DataPersistenceActor(modelContainer: container)

        // Strava starts its ride 2 minutes before `since`; the HealthKit copy starts after it.
        await persistence.upsertRecentData(workouts: [], strava: [storedStravaRide(offset: -120)], sleep: [], hrv: [],
                                           rhr: [], steps: [], weight: [], nutrition: [], vo2max: [])

        await persistence.upsertHealthKitWorkoutsOnly([healthKitRide()], since: start.addingTimeInterval(-60))

        let ids = Set(try ModelContext(container).fetch(FetchDescriptor<StoredWorkout>()).map(\.id))
        XCTAssertEqual(ids, ["strava-1"], "A twin straddling `since` must still be matched, not stored twice")
    }
}
